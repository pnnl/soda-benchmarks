#!/bin/bash
# Cross-compile a soda-generated LLVM IR kernel for an ESP SoC's RISC-V core,
# and stage everything needed to finish the build inside an ESP checkout.
#
# Usage: ll_to_riscv.sh <input.ll> <output.o>
#
# Two things happen here:
#
#   1. <input.ll> is compiled to a RISC-V relocatable object. The IR carries no
#      target triple, so the target is chosen entirely by the flags below.
#   2. An esp-app/ directory is written beside the object holding the driver, the
#      generated test data, the ESP runtime sources and a bare-metal Makefile.
#      For the validated ESP revision, place it under
#      <esp>/soft/common/apps/baremetal/ and build from the SoC directory.
#      See docs/ESPValidation.md for the required ESP environment.
#
# The final link is not attempted here. It needs ESP's own headers
# (esp_accelerator.h, esp_probe.h), its baremetal support library and a RISC-V
# sysroot, none of which are in this container -- see esp-app/README.md.

set -e -o pipefail

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )"
source $SCRIPT_DIR/check_docker.sh

if [ "$#" -ne 2 ]; then
  echo "Usage: $0 <input.ll> <output.o>" >&2
  exit 1
fi

INPUT_LL="$1"
OUTPUT_OBJ="$2"

if [ ! -f "$INPUT_LL" ]; then
  echo "Error: $INPUT_LL not found" >&2
  exit 1
fi

CC="${CC:-clang}"
# Ariane/CVA6 as ESP configures it: 64-bit, with the M, A, F, D and C extensions.
RISCV_TARGET="${RISCV_TARGET:-riscv64-unknown-elf}"
RISCV_MARCH="${RISCV_MARCH:-rv64imafdc}"
RISCV_MABI="${RISCV_MABI:-lp64d}"

SODAP_DIR="${SODAP_DIR:-/workspaces/soda/soda-benchmarks/examples/soda-plugins}"
TESTDATA_DIR="${TESTDATA_DIR:-$(cd "$(dirname "$INPUT_LL")" && pwd)}"
APP_NAME="${ESP_APP_NAME:-soda_kernel}"

mkdir -p "$(dirname "$OUTPUT_OBJ")"
OUTPUT_DIR=$(cd "$(dirname "$OUTPUT_OBJ")" && pwd)
APP_DIR="$OUTPUT_DIR/esp-app"

echo "[ll_to_riscv] target : $RISCV_TARGET -march=$RISCV_MARCH -mabi=$RISCV_MABI"
$DOCKER_RUN $CC --target=$RISCV_TARGET -march=$RISCV_MARCH -mabi=$RISCV_MABI \
  -O2 -c "$INPUT_LL" -o "$OUTPUT_OBJ"
echo "[ll_to_riscv] wrote  : $OUTPUT_OBJ"

# ---------------------------------------------------------------------------
# Stage the application directory
# ---------------------------------------------------------------------------
mkdir -p "$APP_DIR"
cp "$OUTPUT_OBJ" "$APP_DIR/kernel.o"
# ESP's baremetal examples pair `APPNAME := mm` with `mm.c`, so name the driver
# after the application and let common_bare.mk's own rule pick it up.
cp "$SCRIPT_DIR/lib/soda_testbench_main.c" "$APP_DIR/$APP_NAME.c"

if [ -f "$TESTDATA_DIR/testdata.h" ]; then
  cp "$TESTDATA_DIR/testdata.h" "$APP_DIR/testdata.h"
else
  echo "[ll_to_riscv] WARNING: $TESTDATA_DIR/testdata.h not found;" >&2
  echo "  esp-app/ will not build until you add it (python torchscript.py" >&2
  echo "  --emit-testdata output/testdata.h)" >&2
fi

for f in lib/sodap/ExecutionEngine/EspRuntime.cpp \
         include/sodap/ExecutionEngine/ESPRuntime.h \
         lib/sodap/ExecutionEngine/esp_prof.c \
         include/sodap/ExecutionEngine/esp_prof.h; do
  if [ -f "$SODAP_DIR/$f" ]; then
    # esp-app/ is flat, so the in-tree include path becomes a bare filename.
    sed 's|#include "sodap/ExecutionEngine/|#include "|' \
      "$SODAP_DIR/$f" > "$APP_DIR/$(basename $f)"
  else
    echo "[ll_to_riscv] WARNING: $SODAP_DIR/$f not found; esp-app/ is missing the runtime" >&2
  fi
done

cat > "$APP_DIR/Makefile" <<MAKEFILE
# Generated by scripts/ll_to_riscv.sh.
#
# Build this inside an ESP checkout: copy this directory to
# <esp>/soft/common/apps/baremetal/$APP_NAME/ and run the application-baremetal
# target from the SoC directory. common_bare.mk supplies the RISC-V toolchain,
# the linker script and the ESP support library. \$(APPNAME).c is the one
# convention ESP's own baremetal examples all follow.
#
# Two things common_bare.mk cannot do on its own, both handled below:
#
# 1. C++. It globs \$(wildcard *.c), defines CC but no CXX, has no %.o:%.cpp
#    rule and compiles -std=gnu99, so EspRuntime.cpp is never seen. The rule
#    below supplies one locally. Nothing here needs libstdc++ -- no exceptions,
#    no RTTI, no static constructors, no operator new -- so -fno-exceptions
#    -fno-rtti against the freestanding target is enough. esp_prof.c is plain C
#    and common_bare.mk picks it up by itself.
#
# 2. kernel.o. It is a prebuilt RISC-V object (soda-opt lowered the kernel and
#    clang cross-compiled it), not built from a .c, so nothing puts it in the
#    link.
#
# Both are solved by appending to OBJS *after* the include: common_bare.mk
# expands \$(OBJS) inside the .exe recipe, a deferred expansion, even though the
# rule's prerequisite list was already fixed when it was read. That reaches the
# link line but not the dependency graph, so an object that must be *built*
# also needs naming as a prerequisite of \$(EXE).
APPNAME := $APP_NAME

CFLAGS += -I.

include \$(DRIVERS)/common_bare.mk

CXX      := \$(CROSS_COMPILE)g++
# Reuse the C flags so the ABI matches exactly, minus the C-only dialect flag.
CXXFLAGS := \$(filter-out -std=gnu99,\$(CFLAGS)) -fno-exceptions -fno-rtti

\$(BUILD_PATH)/EspRuntime.o: EspRuntime.cpp ESPRuntime.h
	\$(CXX) \$(CXXFLAGS) -c \$< -o \$@

OBJS += \$(BUILD_PATH)/EspRuntime.o
OBJS += \$(CURDIR)/kernel.o
\$(EXE): \$(BUILD_PATH)/EspRuntime.o
MAKEFILE

cat > "$APP_DIR/README.md" <<README
# $APP_NAME — ESP baremetal application

Generated by \`scripts/ll_to_riscv.sh\`. This stages the application sources and
object; it still needs ESP headers, support libraries, matching SoC support
files, startup/linker configuration, and a RISC-V toolchain. See
\`docs/ESPValidation.md\` in the soda-benchmarks source for the tested revisions
and the local ESP startup/linker patch used for the recorded board run.

| File | What it is |
|---|---|
| \`kernel.o\` | the PolyBench kernel, lowered by soda-opt and cross-compiled for RISC-V. Defines \`forward_kernel\`; its external runtime and memory-helper references depend on the marshalling and optimization mode. |
| \`$APP_NAME.c\` | the driver — calls \`forward_kernel\` and diffs the result against a PyTorch golden. Identical to \`scripts/lib/soda_testbench_main.c\`, named after the application because that is the pairing ESP's baremetal examples use. |
| \`testdata.h\` | the inputs and the golden, generated by \`torchscript.py --emit-testdata\`. |
| \`EspRuntime.cpp\`, \`ESPRuntime.h\` | the ESP runtime the kernel's \`esp_*\` calls resolve to. Uses generic register writes and supplied shared-memory strides, but still selects the FFN device and provides Q16.16 conversion helpers. |
| \`esp_prof.c\`, \`esp_prof.h\` | region timing support for generated instrumentation and the application's profiling report. |
| \`Makefile\` | \`APPNAME\` plus \`include \\\$(DRIVERS)/common_bare.mk\`. |

## Building

On the host, set \`ESP_ROOT\`, \`ESP_SOC_DIR\`, and \`CROSS_COMPILE\` to the
matching ESP checkout, SoC directory and RISC-V toolchain prefix. From this
staged directory, use a fresh application name/output to avoid a stale binary:

\`\`\`sh
set -euo pipefail
app_target="\$ESP_ROOT/soft/common/apps/baremetal/$APP_NAME"
exe="\$ESP_SOC_DIR/soft-build/ariane/baremetal/$APP_NAME.exe"
test ! -e "\$app_target"
test ! -e "\$exe"
cp -R . "\$app_target"
make -C "\$ESP_SOC_DIR" $APP_NAME-baremetal CROSS_COMPILE="\$CROSS_COMPILE"
test -s "\$exe"
undefined_symbols=\$("\${CROSS_COMPILE}nm" --undefined-only "\$exe")
test -z "\$undefined_symbols"
\`\`\`

Do not use top-level ESP \`make -B\`: it can regenerate the SoC configuration
from defaults and remove the accelerator mapping. Check the fresh executable:
the outer make target was observed to hide a recursive build failure. The
legacy \`--stage binary\` helper assumes a different ESP directory layout;
the manual procedure above is the validated path for this checkout.

\`EspRuntime.cpp\` includes \`<esp_accelerator.h>\` and \`<esp_probe.h>\`, which
\`common_bare.mk\` puts on the include path. It probes for
\`sld,ffn_sysc_catapult\` (device 0x074), so that accelerator has to be in the
SoC configuration.

The generated \`Makefile\` adds a local C++ rule for \`EspRuntime.cpp\` and puts
\`kernel.o\` on the link line -- \`common_bare.mk\` does neither by itself. It
was verified against ESP's \`common_bare.mk\` on a VC707; see the comments in
the Makefile if your checkout's copy differs.

## Running

Load the resulting binary the way you load any ESP baremetal application. The
driver prints one line per parameter set, then \`TEST PASSED\` or
\`TEST FAILED\` with the maximum deviation. Some deviation is expected: the
accelerator computes in Q16.16 fixed point while the golden is float.
