#!/bin/bash

set -e -o pipefail

# Check if docker is available or if the needed binaries are available
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )"
source $SCRIPT_DIR/check_docker.sh

# Bambu needs the environment from its settings.sh (BAMBU_HLS, backend and
# compiler paths). Source it for local installs if it was not done already.
if [ -z "$DOCKER_RUN" ] && [ -z "$BAMBU_HLS" ] && command -v bambu &> /dev/null; then
  BAMBU_SETTINGS_SH="$(dirname "$(command -v bambu)")/../settings.sh"
  if [ -f "$BAMBU_SETTINGS_SH" ]; then
    source "$BAMBU_SETTINGS_SH"
  fi
fi

if [ "$#" -ne 2 ]; then
  echo "Usage: $0 <input.ll> <output.v>" >&2
  exit 1
fi


BAMBU_DEVICE="${BAMBU_DEVICE:-asap7-BC}"
BAMBU_MEMPOLICY="${BAMBU_MEMPOLICY:-NO_BRAM}"
BAMBU_CLOCK_PERIOD="${BAMBU_CLOCK_PERIOD:-5}"
BAMBU_RUN_SIMULATION="${BAMBU_RUN_SIMULATION:-false}"
BAMBU_IP_INTEGRATION="${BAMBU_IP_INTEGRATION:-false}"


OUTPUT_DIR=$(pwd)/$(dirname $2)
mkdir -p $OUTPUT_DIR
OUTPUT_NAME=$(basename $2)
OUTPUT_PATH=$OUTPUT_DIR/$OUTPUT_NAME

# set -x

cp $1 $OUTPUT_DIR/input.ll
pushd $OUTPUT_DIR

SIMULATION_ARGS=""
if [ "$BAMBU_RUN_SIMULATION" = "true" ]; then
  TB_SUFFIX="--simulate --simulator=VERILATOR --parallel-backend=$(nproc)"
  # The file forward_kernel_testbench.c is generated by another tool
  # it may be in the current directory or in a relative path from 1 to 3 directories below. Check if we can find it.
  if [ -f "forward_kernel_testbench.c" ]; then
    SIMULATION_ARGS="--generate-tb=forward_kernel_testbench.c $TB_SUFFIX"
  elif [ -f "../forward_kernel_testbench.c" ]; then
    SIMULATION_ARGS="--generate-tb=../forward_kernel_testbench.c $TB_SUFFIX"
  elif [ -f "../../forward_kernel_testbench.c" ]; then
    SIMULATION_ARGS="--generate-tb=../../forward_kernel_testbench.c $TB_SUFFIX"
  elif [ -f "../../../forward_kernel_testbench.c" ]; then
    SIMULATION_ARGS="--generate-tb=../../../forward_kernel_testbench.c $TB_SUFFIX"
  else
    echo "Error: forward_kernel_testbench.c not found in the expected locations."
    exit 1
  fi
fi

# Bambu now writes its library components to a separate file by default. Keep
# a single HDL file, so that 06_verilog.v (and the OpenROAD config) is complete.
COMPONENTS_ARGS="--generate-components=mix"

IP_INTEGRATION_ARGS=""
if [ "$BAMBU_IP_INTEGRATION" = "true" ]; then
  # Check for required environment variables/files
  if [ -z "$IP_CONSTRAINTS" ]; then
    echo "Error: BAMBU_IP_INTEGRATION is true but IP_CONSTRAINTS is not set." >&2
    exit 1
  fi
  if [ ! -f "$IP_CONSTRAINTS" ]; then
    echo "Error: IP_CONSTRAINTS file '$IP_CONSTRAINTS' not found." >&2
    exit 1
  fi
  if [ -z "$IP_MODULE_LIB" ] || [ ! -f "$IP_MODULE_LIB" ]; then
    echo "Error: IP_MODULE_LIB is not set or file not found." >&2
    exit 1
  fi
  if [ -z "$IP_C_EXCLUDE" ]; then
    echo "Error: IP_C_EXCLUDE is not set." >&2
    exit 1
  fi
  if [ -z "$IP_VERILOG_INPUTS" ]; then
    echo "Error: IP_VERILOG_INPUTS is not set." >&2
    exit 1
  fi

  # Compose the IP integration arguments
  IP_INTEGRATION_ARGS="$IP_MODULE_LIB $IP_CONSTRAINTS --C-no-parse=$IP_C_EXCLUDE --file-input-data=$IP_VERILOG_INPUTS"
  # Generate the PandA/Bambu components library in a separate file
  COMPONENTS_ARGS="--generate-components=separate"
fi

$DOCKER_RUN \
bambu -v3 --print-dot \
	-lm \
	--compiler=I386_CLANG19  \
	--device=$BAMBU_DEVICE \
	--clock-period=$BAMBU_CLOCK_PERIOD \
	--experimental-setup=BAMBU-BALANCED-MP \
	--channels-number=2 \
	--memory-allocation-policy=$BAMBU_MEMPOLICY \
	--disable-function-proxy \
  $COMPONENTS_ARGS \
  $SIMULATION_ARGS \
  $IP_INTEGRATION_ARGS \
	--top-fname=forward_kernel \
	input.ll 2>&1 | tee bambu-log

cp forward_kernel.v 06_verilog.v


# TODO: This is required for different runs of change location with exposed ports
# Optional per-recipe testbench patch hook.
