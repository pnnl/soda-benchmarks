#!/bin/bash

set -e -o pipefail

# Check if docker is available or if the needed binaries are available
SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" &> /dev/null && pwd )"
source $SCRIPT_DIR/check_docker.sh

# Bambu needs the environment from its settings.sh (BAMBU_HLS, backend and
# compiler paths). Source it for local installs if it was not done already.
if [ -z "$DOCKER_RUN" ] && [ -z "$BAMBU_HLS" ] && command -v bambu &> /dev/null; then
  BAMBU_SETTINGS_SH="$(dirname "$(command -v bambu)")/../settings.sh"
  if [ -f "$BAMBU_SETTINGS_SH" ]; then
    source "$BAMBU_SETTINGS_SH"
  fi
fi

if [ "$#" -ne 2 ]; then
  echo "Usage: $0 <input.c> <output.v>" >&2
  exit 1
fi

BAMBU_DEVICE="${BAMBU_DEVICE:-nangate45}"
BAMBU_MEMPOLICY="${BAMBU_MEMPOLICY:-NO_BRAM}"
BAMBU_CLOCK_PERIOD="${BAMBU_CLOCK_PERIOD:-5}"
BAMBU_RUN_SIMULATION="${BAMBU_RUN_SIMULATION:-false}"


OUTPUT_DIR=$(pwd)/$(dirname $2)
mkdir -p $OUTPUT_DIR
OUTPUT_NAME=$(basename $2)
OUTPUT_PATH=$OUTPUT_DIR/$OUTPUT_NAME

# set -x

cp $1 $OUTPUT_DIR/input.c
pushd $OUTPUT_DIR

SIMULATION_FILE_PATH="${BAMBU_TESTBENCH_FILE}"

SIMULATION_ARGS=""
if [ "$BAMBU_RUN_SIMULATION" = "true" ]; then
  TB_SUFFIX="--simulate --simulator=VERILATOR --parallel-backend=$(nproc)"
  # The file $SIMULATION_FILE_PATH is generated by another tool
  # it may be in the current directory or in a relative path from 1 to 3 directories below. Check if we can find it.
  if [ -f "$SIMULATION_FILE_PATH" ]; then
    SIMULATION_ARGS="--generate-tb=$SIMULATION_FILE_PATH $TB_SUFFIX"
  elif [ -f "../$SIMULATION_FILE_PATH" ]; then
    SIMULATION_ARGS="--generate-tb=../$SIMULATION_FILE_PATH $TB_SUFFIX"
  elif [ -f "../../$SIMULATION_FILE_PATH" ]; then
    SIMULATION_ARGS="--generate-tb=../../$SIMULATION_FILE_PATH $TB_SUFFIX"
  elif [ -f "../../../$SIMULATION_FILE_PATH" ]; then
    SIMULATION_ARGS="--generate-tb=../../../$SIMULATION_FILE_PATH $TB_SUFFIX"
  else
    echo "Error: $SIMULATION_FILE_PATH not found in the expected locations."
    exit 1
  fi
fi

$DOCKER_RUN \
bambu -v3 --print-dot \
		-lm \
		--compiler=I386_CLANG19  \
		--device=$BAMBU_DEVICE \
		--clock-period=$BAMBU_CLOCK_PERIOD \
		--experimental-setup=BAMBU-BALANCED-MP \
		--channels-number=2 \
		--memory-allocation-policy=$BAMBU_MEMPOLICY \
		--disable-function-proxy \
		--generate-components=mix \
    $SIMULATION_ARGS \
		--top-fname=forward_kernel \
		input.c 2>&1 | tee bambu-log

cp forward_kernel.v 06_verilog.v

# If simulation was requested, copy results from results.txt to 07_results.txt
if [ "$BAMBU_RUN_SIMULATION" = "true" ]; then
  # Newer bambu writes the same timing data to bambu_time_simulation.txt
  if [ -f results.txt ]; then
    cp results.txt 07_results.txt
  elif [ -f bambu_time_simulation.txt ]; then
    cp bambu_time_simulation.txt 07_results.txt
  else
    echo "No results.txt found, skipping copying results."
  fi
fi

# Patch OpenROAD scripts generated by bambu only for specific devices
case "$BAMBU_DEVICE" in
  asap7-BC|asap7-TC|asap7-WC|nangate45)
    BAMBUDIR=$OUTPUT_DIR
    KERNELNAME=forward_kernel
    # If asap7-BC, this removes -BC from the device name leaving just asap7
    PLATFORM=${BAMBU_DEVICE%-*}
    source ${SCRIPT_DIR}/patch_openroad_synt.sh
    ;;
esac

popd
  
set +x