"""Regenerate finite binary-fraction fixtures and an independent GEMM oracle."""
from pathlib import Path
import argparse
import struct

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("output_dir", type=Path)
root = parser.parse_args().output_dir
(root / "Inputs").mkdir(parents=True, exist_ok=True)


def bits(value):
    return struct.unpack("<I", struct.pack("<f", value))[0]


inputs, expected = [], []
for case in range(3):
    if case == 0:
        c, a, b = [1.0] * 96, [1.0] * 128, [1.0] * 192
        beta, alpha = 1.0, 1.0
    else:
        c = [((i * 7 + case) % 17 - 8) / 4 for i in range(96)]
        a = [((i * 5 + case) % 13 - 6) / 2 for i in range(128)]
        b = [((i * 3 + case) % 11 - 5) / 4 for i in range(192)]
        beta, alpha = (-0.5, 1.25) if case == 1 else (1.5, -0.75)
    gold = []
    for i in range(8):
        for j in range(12):
            dot = sum(a[i * 16 + k] * b[k * 12 + j] for k in range(16))
            gold.append(beta * c[i * 12 + j] + alpha * dot)
    inputs.append(list(map(bits, c + a + b + [float("nan")] * 96 + [beta, alpha])))
    expected.append(list(map(bits, gold)))

header = [
    "// SPDX-License-Identifier: Apache-2.0 WITH LLVM-exception",
    "// Generated by make-vectors.py; all GEMM arithmetic is exact for these inputs.",
    "#include <stdint.h>",
]
for name, data in (("inputs", inputs), ("expected", expected)):
    header.append(f"static const uint32_t {name}[3][{len(data[0])}] = {{")
    for row in data:
        header.append("  {")
        for start in range(0, len(row), 8):
            header.append("    " + ", ".join(f"0x{x:08x}u" for x in row[start:start + 8]) + ",")
        header.append("  },")
    header.append("};")
(root / "vectors.h").write_text("\n".join(header) + "\n")
for name, values in (("input_1.hex", inputs[1]), ("gold_1.hex", expected[1])):
    (root / "Inputs" / name).write_text("".join(f"{value:08x}\n" for value in values))
